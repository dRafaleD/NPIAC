def test_ollama_redirects_are_not_followed() -> None:
    class RedirectHandler(BaseHTTPRequestHandler):
        sink_hits = 0

        def do_POST(self) -> None:
            if self.path == "/sink":
                type(self).sink_hits += 1
                self.send_response(200)
                self.end_headers()
                self.wfile.write(b'{}')
                return
            self.send_response(307)
            self.send_header("Location", "/sink")
            self.end_headers()

        def log_message(self, format: str, *args: object) -> None:
            return

    server = ThreadingHTTPServer(("127.0.0.1", 0), RedirectHandler)
    thread = threading.Thread(target=server.serve_forever, daemon=True)
    thread.start()
    try:
        with pytest.raises(OllamaError):
            OllamaClient(f"http://127.0.0.1:{server.server_port}", timeout=2).generate("model", "prompt")
    finally:
        server.shutdown()
        server.server_close()
        thread.join(timeout=2)
    assert RedirectHandler.sink_hits == 0


def test_ollama_rejects_invalid_timeout_status_and_oversized_response() -> None:
    with pytest.raises(OllamaError):
        OllamaClient(timeout=0, opener=lambda request, timeout: None).generate("model", "prompt")

    class BadStatusResponse:
        status = 500

        def __enter__(self):
            return self

        def __exit__(self, *args):
            return False

        def read(self, limit: int) -> bytes:
            return b"{}"

    with pytest.raises(OllamaError):
        OllamaClient(opener=lambda request, timeout: BadStatusResponse()).generate("model", "prompt")

    class HugeResponse(BadStatusResponse):
        status = 200

        def read(self, limit: int) -> bytes:
            return b"x" * limit

    with pytest.raises(OllamaError):
        OllamaClient(opener=lambda request, timeout: HugeResponse()).generate("model", "prompt")


