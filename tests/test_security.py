def test_git_scan_uses_nul_delimited_argument_list_and_rejects_malicious_names(tmp_path: Path, monkeypatch) -> None:
    (tmp_path / ".git").mkdir()
    _write(tmp_path, "safe.py", "SAFE = True\n")
    run_calls: list[tuple[list[str], dict[str, object]]] = []
    popen_calls: list[tuple[list[str], dict[str, object]]] = []

    def fake_run(arguments, **kwargs):
        run_calls.append((arguments, kwargs))
        return SimpleNamespace(stdout=str(tmp_path) + "\n")

    class FakeStdout:
        def __init__(self) -> None:
            self.payloads = [b"safe.py\0bad\nname.py\0", b""]

        def read(self, limit: int) -> bytes:
            return self.payloads.pop(0)

        def close(self) -> None:
            return

    class FakeProcess:
        def __init__(self) -> None:
            self.stdout = FakeStdout()

        def wait(self, timeout: int) -> int:
            return 0

        def kill(self) -> None:
            return

    def fake_popen(arguments, **kwargs):
        popen_calls.append((arguments, kwargs))
        return FakeProcess()

    monkeypatch.setattr(scanner.shutil, "which", lambda name: "git")
    monkeypatch.setattr(scanner.subprocess, "run", fake_run)
    monkeypatch.setattr(scanner.subprocess, "Popen", fake_popen)
    snapshot = scan_repository(tmp_path)

    assert snapshot.paths == ("safe.py",)
    assert len(run_calls) == 1
    ls_files_call = popen_calls[0]
    assert "-z" in ls_files_call[0]
    assert "shell" not in ls_files_call[1]


def test_filesystem_fallback_honors_gitignore_and_npiacignore(tmp_path: Path) -> None:
    _write(tmp_path, ".gitignore", "git-ignored.py\nprivate/data\n")
    _write(tmp_path, ".npiacignore", "npiac-ignored.py\n")
    _write(tmp_path, "git-ignored.py", "GIT_SECRET = 'hidden'\n")
    _write(tmp_path, "npiac-ignored.py", "NPIAC_SECRET = 'hidden'\n")
    _write(tmp_path, "private/data/nested.py", "NESTED_SECRET = 'hidden'\n")
    _write(tmp_path, "safe.py", "SAFE = True\n")

    context = analyze_repository(tmp_path)
    rendered = render_context(context)
    prompt = build_ai_prompt(tmp_path, context)
    for forbidden in (
        "git-ignored.py",
        "npiac-ignored.py",
        "private/data/nested.py",
        "GIT_SECRET",
        "NPIAC_SECRET",
        "NESTED_SECRET",
    ):
        assert forbidden not in rendered
        assert forbidden not in prompt


def test_ignore_negation_cannot_reinclude_sensitive_files(tmp_path: Path) -> None:
    _write(tmp_path, ".npiacignore", "!.env\n!credentials.json\n!private.pem\n!.npmrc\n")
    _write(tmp_path, ".env", "PASSWORD=env-secret\n")
    _write(tmp_path, "credentials.json", '{"token":"credential-secret"}\n')
    _write(tmp_path, "private.pem", f"{_PRIVATE_KEY_BEGIN}\nsecret\n{_PRIVATE_KEY_END}\n")
    _write(tmp_path, ".npmrc", "//registry/:_authToken=npm-secret\n")

    snapshot = scan_repository(tmp_path)
    assert not ({".env", "credentials.json", "private.pem", ".npmrc"} & set(snapshot.paths))


