def test_oversized_git_listing_falls_back_to_bounded_filesystem_scan(tmp_path: Path, monkeypatch) -> None:
    (tmp_path / ".git").mkdir()
    _write(tmp_path, "safe.py", "SAFE = True\n")

    class FakeStdout:
        sent = False

        def read(self, limit: int) -> bytes:
            if self.sent:
                return b""
            self.sent = True
            return b"safe.py\0" * 10

        def close(self) -> None:
            return

    class FakeProcess:
        def __init__(self) -> None:
            self.stdout = FakeStdout()

        def wait(self, timeout: int) -> int:
            return 0

        def kill(self) -> None:
            return

    monkeypatch.setattr(scanner, "MAX_GIT_OUTPUT_BYTES", 16)
    monkeypatch.setattr(scanner.shutil, "which", lambda name: "git")
    monkeypatch.setattr(
        scanner.subprocess,
        "run",
        lambda arguments, **kwargs: SimpleNamespace(stdout=str(tmp_path) + "\n"),
    )
    monkeypatch.setattr(scanner.subprocess, "Popen", lambda arguments, **kwargs: FakeProcess())

    snapshot = scan_repository(tmp_path)
    assert snapshot.paths == ("safe.py",)
    assert not snapshot.is_git
    assert any("Git scanning failed" in warning for warning in snapshot.warnings)
